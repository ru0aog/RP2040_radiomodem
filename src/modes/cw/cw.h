// src/modes/cw/cw.h  
// ============================================================================  
// CW (морзянка) — простейшая мода. TX: несущая с ключевой манипуляцией  
// на частоте тона. RX: детектор тона → разбор точек/тире → символы.  
// Все частоты — Гц.  
// ============================================================================  
#pragma once  
#include <Arduino.h>  
#include "../modes.h"  
  
// ---------- Общие параметры ----------  
#define CW_TONE_OFFSET_HZ   600u     // смещение тона от несущей, Гц  
#define CW_DEFAULT_WPM      15u      // скорость, слов в минуту (PARIS)  
  
// ---------- RX API ----------  
void cw_rx_init(uint32_t center_hz);        // центр приёма, Гц  
void cw_rx_push(int16_t sample);            // 15625 sps, моно  
void cw_rx_set_wpm(uint8_t wpm);            // ожидаемая скорость  
  
// ---------- TX API ----------  
// Текст в ASCII, "." "-" и пробелы — в тон/паузы. Через trx_control.  
// Возвращает длительность передачи в мс; 0 = не реализовано.  
uint32_t cw_tx_frame(const uint8_t *payload, uint16_t len);  
void cw_tx_set_wpm(uint8_t wpm);            // скорость телеграфа  
// Прямой ключ (для ручной передачи/встроенного ключа):  
void cw_tx_key(bool down);                  // down=true → несущая  
void cw_rx_stop(void);    // сброс состояния декодера (idle, паттерн, тайминги)
  
// ---------- Регистрация ----------  
const ModeIface *cw_mode_iface(void);
