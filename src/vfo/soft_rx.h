// src/vfo/soft_rx.h  
// ============================================================================  
// Квадратурный гетеродин приёмника (soft_rx): 4-тактовая PIO-программа  
// на pio1 выдаёт на 2 соседних пина (GP0=I, GP1=Q) меандр со сдвигом  
// 90° для SDR-смесителя.  
//  
// Движок регистрируется в менеджере vfo.cpp как VFO_BACKEND_SOFT_RX;  
// прямой вызов функций из скетча не требуется, кроме диагностики.  
// ============================================================================  
#pragma once  
#include <Arduino.h>  
#include "vfo.h"              // VfoEngine  
  
// ============================================================================  
// ДВИЖОК ДЛЯ МЕНЕДЖЕРА (регистрируется в vfo_init через vfo_set_backend)  
// ============================================================================  
// Возвращает таблицу колбэков движка (init/start/stop/tone/poll/hz).  
const VfoEngine *vfo_engine_soft_rx(void);  
  
// ============================================================================  
// ДИАГНОСТИКА / СЕРВИС (вызывать из скетча при отладке)  
// ============================================================================  
// Разовый дамп регистров SM: ctrl/clkdiv/execctrl/enabled + lo_hz.  
// Показывает, реально ли крутится генератор.  
void     soft_rx_quad_debug(void);  
  
// Фактическая частота квадратурного LO, Гц (0 — не запущен).  
// Дублирует VfoEngine::actual_hz — удобно без доступа к таблице.  
uint32_t soft_rx_quad_lo_hz(void);
